def seed_schemes():
    engine = create_engine(DATABASE_URL)
    with engine.connect() as conn:
        for s in SCHEMES_DATA:
            sql = text("""
                INSERT INTO schemes (
                    scheme_code, name, category_id, department, administering_authority,
                    description, benefit_summary, benefit_type, benefit_amount,
                    eligibility_summary, application_instructions, official_url,
                    application_start_date, application_end_date, status,
                    is_duplicate_check_enabled, created_by, created_at, updated_at,
                    beneficiary_categories, verification_status
                ) VALUES (
                    :scheme_code, :name, :category_id, :department, :administering_authority,
                    :description, :benefit_summary, :benefit_type, :benefit_amount,
                    :eligibility_summary, :application_instructions, :official_url,
                    '2026-01-01', '2026-12-31', 'PUBLISHED',
                    1, 'SYSTEM_ADMIN', NOW(), NOW(),
                    :beneficiary_categories, :verification_status
                )
                ON DUPLICATE KEY UPDATE
                    name = VALUES(name),
                    category_id = VALUES(category_id),
                    department = VALUES(department),
                    administering_authority = VALUES(administering_authority),
                    description = VALUES(description),
                    benefit_summary = VALUES(benefit_summary),
                    benefit_type = VALUES(benefit_type),
                    benefit_amount = VALUES(benefit_amount),
                    eligibility_summary = VALUES(eligibility_summary),
                    application_instructions = VALUES(application_instructions),
                    official_url = VALUES(official_url),
                    beneficiary_categories = VALUES(beneficiary_categories),
                    verification_status = VALUES(verification_status),
                    status = 'PUBLISHED',
                    updated_at = NOW();
            """)
            conn.execute(sql, s)
        conn.commit()
        print(f"Successfully seeded/updated {len(SCHEMES_DATA)} schemes in nagriksetu_swd.")

if __name__ == '__main__':
    seed_schemes()
