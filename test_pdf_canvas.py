from reportlab.pdfgen import canvas

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count):
        if self._pageNumber > 1:
            self.saveState()
            self.setFont("Helvetica", 9)
            self.setFillColor(colors.HexColor("#475569"))
            # Header
            self.drawString(54, 800, "NagrikSetu SWD — Academic Project Report: About the Service")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(54, 792, 541, 792)
            # Footer
            self.line(54, 45, 541, 45)
            self.drawRightString(541, 32, f"Page {self._pageNumber} of {page_count}")
            self.drawString(54, 32, "Confidential — Academic Evaluation Only")
            self.restoreState()

print("NumberedCanvas initialized successfully!")
